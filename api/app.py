"""Hospital Models API — FastAPI prototype serving the visit-risk and claim-outcome models.

Demo only: no authentication or HTTPS. Do not expose publicly or use with real patient data.
Model files (risk_model.pkl, claim_rf_model.pkl) are generated by notebooks/Phase3_Modeling.ipynb
and must be placed in this folder before starting the server.
"""

from datetime import datetime, timezone
import hashlib

import joblib
import pandas as pd
from fastapi import FastAPI
from pydantic import BaseModel

app = FastAPI(title="Hospital Models API")

# Load models (scikit-learn pipelines saved with joblib).
# Only load model files you generated yourself: pickle files can execute code when loaded.
risk_model = joblib.load("risk_model.pkl")
claim_rf_model = joblib.load("claim_rf_model.pkl")  # advanced claim model


# Input schemas (Pydantic validates field presence and types; invalid requests return HTTP 422)
class RiskInput(BaseModel):
    age: int
    gender: str
    chronic_flag: int
    city: str
    department: str
    visit_type: str
    length_of_stay_hours: float
    visit_frequency: float
    avg_length_of_stay: float
    provider_rejection_rate: float
    days_since_registration: int
    visit_month: int
    visit_weekday: int


class ClaimInput(BaseModel):
    age: int
    gender: str
    chronic_flag: int
    city: str
    department: str
    visit_type: str
    length_of_stay_hours: float
    billed_amount: float
    approved_amount: float
    payment_days: float
    visit_frequency: float
    avg_length_of_stay: float
    provider_rejection_rate: float
    days_since_registration: int
    visit_month: int
    visit_weekday: int


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def to_frame(input_data: BaseModel) -> pd.DataFrame:
    # The trained pipelines select columns by name (ColumnTransformer), so the model
    # must receive a one-row DataFrame with named columns, not a plain list of values.
    return pd.DataFrame([input_data.model_dump()])


@app.get("/health")
def health_check():
    return {"status": "OK", "timestamp": utc_now()}


@app.post("/predict/risk")
def predict_risk(input_data: RiskInput):
    features = to_frame(input_data)
    prediction = str(risk_model.predict(features)[0])
    # Note: an MD5 hash of low-variety inputs is not anonymisation (see Governance report).
    input_hash = hashlib.md5(features.to_json().encode()).hexdigest()
    print(f"[{utc_now()}] Risk Prediction: {prediction}, hash: {input_hash}")
    return {"risk_score": prediction, "timestamp": utc_now()}


@app.post("/predict/claim")
def predict_claim(input_data: ClaimInput):
    features = to_frame(input_data)
    prediction = str(claim_rf_model.predict(features)[0])
    input_hash = hashlib.md5(features.to_json().encode()).hexdigest()
    print(f"[{utc_now()}] Claim Prediction: {prediction}, hash: {input_hash}")
    return {"claim_status": prediction, "timestamp": utc_now()}
